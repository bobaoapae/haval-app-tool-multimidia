import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const collection = ['Horizonte', 'Pulso', 'Orbita', 'Sereno', 'Eclipse'];
export const shared = path.dirname(fileURLToPath(import.meta.url));
export const sourceRoot = path.resolve(shared, '../..');
export const packageRoot = path.resolve(sourceRoot, '../../Themes/v1.0');

export function contractSource() {
    const source = fs.readFileSync(path.resolve(shared, '../car/carDerivations.js'), 'utf8');
    const match = /^export function getAdjustedSpeed\([\s\S]*?^\}/m.exec(source);
    if (!match) throw new Error('Canonical speed calibration changed shape; review before building.');
    return '// Generated by original-themes/build.mjs from shared/car/carDerivations.js.\n' +
        '(function () { "use strict";\n' + match[0].replace(/^export /, '') +
        '\nwindow.ImpulseContract = { getAdjustedSpeed: getAdjustedSpeed };\n})();\n';
}
export function bundle(name) {
    if (!collection.includes(name)) throw new Error(`Unknown collection theme: ${name}`);
    const root = path.join(sourceRoot, name);
    let html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
    html = html.replace(/<link rel="stylesheet" href="([^"]+)">/g, (_, resource) =>
        `<style>\n${fs.readFileSync(path.resolve(root, resource), 'utf8')}\n</style>`);
    const scripts = [];
    html = html.replace(/<script (?:defer )?src="([^"]+)"(?: defer)?><\/script>/g, (_, resource) => {
        scripts.push(`<script>\n${fs.readFileSync(path.resolve(root, resource), 'utf8').replace(/<\/script/gi, '<\\/script')}\n</script>`);
        return '';
    });
    // Inline scripts do not honor defer. Execute in source order only after the full DOM exists.
    if (!html.includes('</body>') || scripts.length !== 2) throw new Error(`${name}: unexpected entry structure`);
    html = html.replace('</body>', () => scripts.join('\n') + '\n</body>');
    if (/<script[^>]+src=|<link[^>]+href=|<img[^>]+src=|url\(/i.test(html)) {
        throw new Error(`${name}: external resource found. Collection packages must run entirely offline.`);
    }
    return html.replace(/[ \t]+$/gm, '');
}
export function build(names = collection) {
    fs.writeFileSync(path.join(shared, 'contract.js'), contractSource());
    for (const name of names) {
        const root = path.join(sourceRoot, name), output = path.join(packageRoot, name);
        fs.mkdirSync(output, { recursive: true });
        fs.mkdirSync(path.join(root, 'dist'), { recursive: true });
        const html = bundle(name);
        fs.writeFileSync(path.join(root, 'dist/app.html'), html);
        fs.writeFileSync(path.join(output, 'app.html'), html);
        fs.copyFileSync(path.join(root, 'theme.xml'), path.join(output, 'theme.xml'));
        const thumbnail = path.join(root, 'thumbnail.png');
        if (fs.existsSync(thumbnail)) fs.copyFileSync(thumbnail, path.join(output, 'thumbnail.png'));
        console.log(`${name}: ${Buffer.byteLength(html)} bytes, self-contained package.`);
    }
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    build(process.argv.length > 2 ? process.argv.slice(2) : collection);
}
